// completionData 是把命令表揉成各 shell 模板要用的字面量，模板本身保持简单。
type completionData struct {
	CommandsPS    string // 'init', 'root', ...
	CommandsSh    string // init root ...
	RepoPS        string
	RepoBashPipe  string
	RepoZshPipe   string
	RepoFish      string
	FlagsPS       string // PowerShell 哈希表字面量
	ValueFlagsPS  string // 需要值的参数（补全时让位给文件补全）
	BashFlagCase  string
	BashWordCase  string
	ZshFlagCase   string
	ZshWordCase   string
	FishFlagLines string
	FishWordLines string
	WordsPS       string
}

func psList(items []string) string {
	q := make([]string, len(items))
	for i, s := range items {
		q[i] = "'" + strings.ReplaceAll(s, "'", "''") + "'"
	}
	return strings.Join(q, ", ")
}

func buildCompletionData() completionData {
	d := completionData{}
	var cmds, cmdsPS, flagsPS, bashFlags, bashWords, zshFlags, zshWords, fishFlags, fishWords, wordsPS []string
	valueSeen := map[string]bool{}
	var valueFlags []string

	for _, c := range completionCommands {
		cmds = append(cmds, c.Name)
		cmdsPS = append(cmdsPS, "'"+c.Name+"'")

		var flags []string
		for _, f := range c.Flags {
			flags = append(flags, "--"+f.Name)
			if f.HasValue && !valueSeen[f.Name] {
				valueSeen[f.Name] = true
				valueFlags = append(valueFlags, "--"+f.Name)
			}
			line := fmt.Sprintf("complete -c zinc -n '__fish_seen_subcommand_from %s' -l %s", c.Name, f.Name)
			if f.HasValue {
				line += " -r"
			}
			fishFlags = append(fishFlags, line)
		}
		flagsPS = append(flagsPS, fmt.Sprintf("    '%s' = @(%s)", c.Name, psList(flags)))
		bashFlags = append(bashFlags, fmt.Sprintf("            %s) flags=\"%s\" ;;", c.Name, strings.Join(flags, " ")))
		zshFlags = append(zshFlags, fmt.Sprintf("            %s) flags=(%s) ;;", c.Name, strings.Join(flags, " ")))

		if len(c.PositionalWords) > 0 {
			words := strings.Join(c.PositionalWords, " ")
			bashWords = append(bashWords, fmt.Sprintf("        %s) COMPREPLY=( $(compgen -W \"%s\" -- \"$cur\") ); return ;;", c.Name, words))
			zshWords = append(zshWords, fmt.Sprintf("        %s) compadd -- %s; return ;;", c.Name, words))
			fishWords = append(fishWords, fmt.Sprintf("complete -c zinc -n '__fish_seen_subcommand_from %s' -a '%s'", c.Name, words))
			wordsPS = append(wordsPS, fmt.Sprintf("    '%s' = @(%s)", c.Name, psList(c.PositionalWords)))
		}
	}

	repo := repoCommands()
	d.CommandsPS = strings.Join(cmdsPS, ", ")
	d.CommandsSh = strings.Join(cmds, " ")
	d.RepoPS = psList(repo)
	d.RepoBashPipe = strings.Join(repo, "|")
	d.RepoZshPipe = strings.Join(repo, "|")
	d.RepoFish = strings.Join(repo, " ")
	d.FlagsPS = "    " + strings.Join(flagsPS, "\n    ")
	d.ValueFlagsPS = psList(valueFlags)
	d.BashFlagCase = strings.Join(bashFlags, "\n")
	d.BashWordCase = strings.Join(bashWords, "\n")
	d.ZshFlagCase = strings.Join(zshFlags, "\n")
	d.ZshWordCase = strings.Join(zshWords, "\n")
	d.FishFlagLines = strings.Join(fishFlags, "\n")
	d.FishWordLines = strings.Join(fishWords, "\n")
	d.WordsPS = strings.Join(wordsPS, "\n")
	return d
}

const completionPwshTemplate = `# zinc completion (PowerShell 7.2+) — generated by ` + "`zinc completion powershell`" + `
if ($PSVersionTable.PSVersion -lt [version]'7.2') { return }
if (-not (Get-Command zinc -CommandType Application -ErrorAction SilentlyContinue)) { return }

$script:ZincCommands = @({{.CommandsPS}})
$script:ZincRepoCmds = @({{.RepoPS}})
$script:ZincFlags = @{
{{.FlagsPS}}
}
$script:ZincFlagValues = @{ '--lang' = @('zh', 'en'); '--at' = @('08:00', '12:00', '20:00') }
$script:ZincValueFlags = @({{.ValueFlagsPS}})
$script:ZincWords = @{
{{.WordsPS}}
}
$script:ZincNameCache = @{ At = [datetime]::MinValue; Names = @() }

function Get-ZincRepoNames {
    if (((Get-Date) - $script:ZincNameCache.At).TotalSeconds -lt 30) { return $script:ZincNameCache.Names }
    $names = @()
    try { $names = @(& zinc list --names 2>$null) } catch { }
    $script:ZincNameCache = @{ At = Get-Date; Names = @($names) }
    return @($names)
}

function New-ZincResult([string[]]$values, [string]$word, [string]$kind, [string]$tooltip) {
    foreach ($v in $values) {
        if (-not $word -or $v -like "$word*") {
            [System.Management.Automation.CompletionResult]::new($v, $v, $kind, $tooltip)
        }
    }
}

Register-ArgumentCompleter -Native -CommandName zinc -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)

    # 取词用 CommandElements，不用 Extent.Text：AST 文本会裁掉行尾空格，
    # 分不清「刚打完空格」和「词还没打完」。
    $tokens = @($commandAst.CommandElements | Select-Object -Skip 1 |
            ForEach-Object { $_.Extent.Text } | Where-Object { $_ })
    $done = if ($wordToComplete -and $tokens.Count -and $tokens[-1] -eq $wordToComplete) {
        @($tokens | Select-Object -SkipLast 1)
    } else { $tokens }
    # 必须再包一层 @()：if 会把单元素数组展开成标量，$done[-1] 就变成「取最后一个字符」
    $done = @($done)

    $sub = @($done | Where-Object { $_ -notlike '-*' })[0]
    $prev = if ($done.Count) { $done[-1] } else { '' }

    # 1) 固定取值（--lang zh|en、--at 的时间示例）
    if ($script:ZincFlagValues.ContainsKey($prev)) {
        return New-ZincResult $script:ZincFlagValues[$prev] $wordToComplete ParameterValue '取值'
    }

    # 1b) 需要值但没有固定取值（--dest/--password/...）：返回空，让 PowerShell 回退到文件补全
    if ($script:ZincValueFlags -contains $prev) { return }

    # 2) 还没写子命令：补子命令或全局参数
    if (-not $sub) {
        if ($wordToComplete -like '-*') {
            return New-ZincResult @('--lang', '--help') $wordToComplete ParameterName '全局参数'
        }
        return New-ZincResult $script:ZincCommands $wordToComplete Command 'zinc 子命令'
    }

    # 3) 正在打参数：给该子命令的参数，已用过的去掉
    if ($wordToComplete -like '-*') {
        $used = @($done | Where-Object { $_ -like '-*' })
        $cand = @($script:ZincFlags[$sub] | Where-Object { $used -notcontains $_ })
        return New-ZincResult $cand $wordToComplete ParameterName "$sub 的参数"
    }

    # 4) 位置参数：config 动作词、completion 的 shell、仓库名
    if ($script:ZincWords.ContainsKey($sub)) {
        return New-ZincResult $script:ZincWords[$sub] $wordToComplete ParameterValue '取值'
    }
    $positional = @($done | Where-Object { $_ -notlike '-*' } | Select-Object -Skip 1)
    if ($script:ZincRepoCmds -contains $sub -and $positional.Count -eq 0) {
        return New-ZincResult @(Get-ZincRepoNames) $wordToComplete ParameterValue '仓库名'
    }
}
`

const completionBashTemplate = `# zinc completion (bash) — generated by ` + "`zinc completion bash`" + `
_zinc() {
    local cur prev sub i word flags
    COMPREPLY=()
    cur="${COMP_WORDS[COMP_CWORD]}"
    prev="${COMP_WORDS[COMP_CWORD-1]}"
    sub=""
    for ((i=1; i<COMP_CWORD; i++)); do
        word="${COMP_WORDS[i]}"
        [[ "$word" == -* ]] && continue
        sub="$word"
        break
    done

    case "$prev" in
        --lang) COMPREPLY=( $(compgen -W "zh en" -- "$cur") ); return ;;
    esac

    if [[ "$cur" == -* ]]; then
        flags=""
        case "$sub" in
{{.BashFlagCase}}
        esac
        COMPREPLY=( $(compgen -W "$flags --lang --help" -- "$cur") )
        return
    fi

    if [[ -z "$sub" ]]; then
        COMPREPLY=( $(compgen -W "{{.CommandsSh}}" -- "$cur") )
        return
    fi

    case "$sub" in
{{.BashWordCase}}
    esac

    if [[ $COMP_CWORD -eq 2 ]]; then
        case "$sub" in
            {{.RepoBashPipe}}) COMPREPLY=( $(compgen -W "$(zinc list --names 2>/dev/null)" -- "$cur") ); return ;;
        esac
    fi
}
complete -F _zinc zinc
`

const completionZshTemplate = `#compdef zinc
# zinc completion (zsh) — generated by ` + "`zinc completion zsh`" + `
_zinc() {
    local -a commands flags
    commands=( {{.CommandsSh}} )
    if (( CURRENT == 2 )); then
        _describe 'command' commands
        return
    fi
    local sub=${words[2]}
    if [[ ${words[CURRENT]} == -* ]]; then
        case "$sub" in
{{.ZshFlagCase}}
        esac
        _describe 'flag' flags
        return
    fi
    case "$sub" in
{{.ZshWordCase}}
        {{.RepoZshPipe}}) compadd -- ${(f)"$(zinc list --names 2>/dev/null)"}; return ;;
    esac
}
`

const completionFishTemplate = `# zinc completion (fish) — generated by ` + "`zinc completion fish`" + `
complete -c zinc -f
complete -c zinc -n '__fish_use_subcommand' -a '{{.CommandsSh}}'
complete -c zinc -l lang -r -a 'zh en'
complete -c zinc -l help
{{.FishFlagLines}}
{{.FishWordLines}}
complete -c zinc -n '__fish_seen_subcommand_from {{.RepoFish}}' -a '(zinc list --names 2>/dev/null)'
`

var completionTemplates = map[string]*template.Template{}

func init() {
	for name, text := range map[string]string{
		"powershell": completionPwshTemplate,
		"bash":       completionBashTemplate,
		"zsh":        completionZshTemplate,
		"fish":       completionFishTemplate,
	} {
		completionTemplates[name] = template.Must(template.New(name).Parse(text))
	}
}

// completionScript 生成指定 shell 的补全脚本。
func completionScript(shell string) (string, bool) {
	tpl, ok := completionTemplates[shell]
	if !ok {
		return "", false
	}
	var b strings.Builder
	if err := tpl.Execute(&b, buildCompletionData()); err != nil {
		return "", false
	}
	return b.String(), true
}

// cmdCompletion 输出补全脚本；--install 只对 powershell 生效，写好脚本并往 profile 里
// 幂等追加一行 dot-source。
func cmdCompletion(args []string) {
	fs := flag.NewFlagSet("completion", flag.ExitOnError)
	install := fs.Bool("install", false, M.FlagCompletionInstall)
	fs.Parse(reorderArgs(args))
	if fs.NArg() < 1 {
		die(M.UsageCompletion)
	}
	shell := strings.ToLower(fs.Arg(0))
	script, ok := completionScript(shell)
	if !ok {
		die(M.CompletionUnknownShell, shell)
	}
	if !*install {
		fmt.Print(script)
		return
	}
	if shell != "powershell" {
		die(M.CompletionInstallOnlyPwsh)
	}
	if err := installPwshCompletion(script); err != nil {
		die(M.CompletionInstallFailed, err)
	}
}

// installPwshCompletion 把脚本写到 Documents\PowerShell\zinc-completion.ps1，
// 并在 $PROFILE 里追加 dot-source 行（已经有就跳过）。
func installPwshCompletion(script string) error {
	home, err := os.UserHomeDir()
	if err != nil {
		return err
	}
	dir := filepath.Join(home, "Documents", "PowerShell")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	target := filepath.Join(dir, "zinc-completion.ps1")
	// UTF-8 带 BOM：中文路径和中文提示在 Windows PowerShell 里才不会乱码
	body := append([]byte{0xEF, 0xBB, 0xBF}, []byte(script)...)
	if err := writeFileSync(target, body, 0o644); err != nil {
		return err
	}
	fmt.Printf(M.CompletionScriptWritten, target)

	profile := pwshProfilePath()
	if err := os.MkdirAll(filepath.Dir(profile), 0o755); err != nil {
		return err
	}
	line := ". '" + strings.ReplaceAll(target, "'", "''") + "'"
	old, _ := os.ReadFile(profile)
	if strings.Contains(string(old), target) {
		fmt.Printf(M.CompletionProfileHasLine, profile)
		return nil
	}
	f, err := os.OpenFile(profile, os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0o644)
	if err != nil {
		return err
	}
	defer f.Close()
	if _, err := f.WriteString("\n" + line + "\n"); err != nil {
		return err
	}
	fmt.Printf(M.CompletionProfileUpdated, profile)
	return nil
}

// pwshProfilePath 返回 PowerShell 7 的 $PROFILE；找不到 pwsh 时退回约定路径。
func pwshProfilePath() string {
	if p, err := exec.LookPath("pwsh"); err == nil {
		if out, err := hiddenCmd(p, "-NoProfile", "-Command", "[Console]::Out.Write($PROFILE)").Output(); err == nil {
			if s := strings.TrimSpace(string(out)); s != "" {
				return s
			}
		}
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return ""
	}
	return filepath.Join(home, "Documents", "PowerShell", "Microsoft.PowerShell_profile.ps1")
}
